-- Already applied to the Trading Psychology Tracker Supabase project.
-- This script is safe to run again.
create table if not exists public.journal_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  emotion text not null,
  trigger_text text not null default '',
  note text not null,
  root_flaw text not null default '',
  intensity smallint not null default 2 check (intensity between 1 and 4),
  created_at timestamptz not null default now()
);

alter table public.journal_entries enable row level security;

do $$ begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='journal_entries' and policyname='Users read own journal entries') then
    create policy "Users read own journal entries" on public.journal_entries
      for select to authenticated using ((select auth.uid()) = user_id);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='journal_entries' and policyname='Users insert own journal entries') then
    create policy "Users insert own journal entries" on public.journal_entries
      for insert to authenticated with check ((select auth.uid()) = user_id);
  end if;
end $$;

grant select, insert on public.journal_entries to authenticated;
create index if not exists journal_entries_user_created_idx
  on public.journal_entries (user_id, created_at desc);
